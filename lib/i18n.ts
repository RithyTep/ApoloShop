// Helper functions
export function getLanguageConfig(lang: Language): LanguageConfig {
  return LANGUAGE_CONFIG[lang]
}

export function isRTL(lang: Language): boolean {
  return RTL_LANGUAGES.includes(lang)
}

export function getDirection(lang: Language): "ltr" | "rtl" {
  return LANGUAGE_CONFIG[lang].direction
}

// Browser language detection
export function detectBrowserLanguage(): Language {
  if (typeof window === "undefined") return "en"

  const browserLang = navigator.language || (navigator as { userLanguage?: string }).userLanguage || "en"
  const langCode = browserLang.split("-")[0].toLowerCase()

  // Map browser language codes to our supported languages
  const langMap: Record<string, Language> = {
    en: "en",
    km: "kh", // Khmer ISO 639-1 code
    kh: "kh",
    th: "th",
    vi: "vi",
    zh: "zh",
    "zh-cn": "zh",
    "zh-tw": "zh",
    "zh-hk": "zh",
  }

  const fullLangCode = browserLang.toLowerCase()
  if (langMap[fullLangCode]) return langMap[fullLangCode]
  if (langMap[langCode]) return langMap[langCode]

  return "en" // Default to English
}

// Get translation with fallback to English
export function getTranslation(lang: Language): typeof translations.en {
  if (lang === "en" || lang === "kh") {
    return translations[lang]
  }
  // For new languages, return the translations if they exist, otherwise fall back to English
  return (translations as Record<string, typeof translations.en>)[lang] || translations.en
}

